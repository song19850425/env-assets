def expand_doc(doc_text):
    parts = doc_text.split('  ')
    new_parts = []
    for p in parts:
        p = p.strip();
        if not p: continue
        if p in SAMPLE_MAP:
            new_parts.append(p + '（' + SAMPLE_MAP[p] + '）')
        else:
            matched = False
            for key, val in SAMPLE_MAP.items():
                if key in p or p in key:
                    new_parts.append(p + '（' + val + '）')
                    matched = True; break
            if not matched:
                new_parts.append(p)
    return ' | '.join(new_parts)

for fname in ['00-CMA现场核查总表（2023版）.html', '01-CNAS-CL01现场核查总表.html']:
    data = open(fname, encoding='utf-8').read()
    def replace_doc(m):
        item = m.group(0)
        doc_m = re.search(r',doc:\"([^\"]+)\"', item)
        if not doc_m: return item
        new_doc = expand_doc(doc_m.group(1))
        if new_doc != doc_m.group(1):
            item = item.replace(',doc:\"' + doc_m.group(1) + '\"', ',doc:\"' + new_doc + '\"')
        return item
    data = re.sub(r'\{[^}]*id:\"[^\"]+\"[^}]*doc:\"[^\"]*\"[^}]*\}(?=,|\])', replace_doc, data)
    open(fname, 'w', encoding='utf-8').write(data)
    cnt = data.count('示例：')
    print(fname[:10], '注入示例:', cnt, '处')
